/**
 * One character, drawn once on a 64×96 grid and used everywhere: the portraits are the same sprite
 * cropped to its top 64 rows. The front head is its own layer so it can bob and blink over any pose.
 * The maps hold his colours only: `outline` draws the dark line round each finished figure.
 */
export const characterSize = { width: 64, height: 96, bust: 64 };

const empty = (rows: number) => Array<string>(rows).fill('');
const mirror = (row: string) => [...row.padEnd(characterSize.width, '.')].reverse().join('');
const lower = (rows: string[], by: number) => [...empty(by), ...rows];

/** Lays sprite layers over each other; a later one covers the earlier ones wherever it has a pixel. */
const stack = (...layers: string[][]) =>
  Array.from({ length: characterSize.height }, (_, y) =>
    Array.from(
      { length: characterSize.width },
      (_, x) => layers.findLast((layer) => (layer[y]?.[x] ?? '.') !== '.')?.[y][x] ?? '.',
    ).join(''),
  );

/** Traces a figure: every empty pixel beside a coloured one turns dark. Lines already drawn do not grow another. */
const outline = (rows: string[]) => {
  const coloured = (x: number, y: number) => !'.K'.includes(rows[y]?.[x] ?? '.');
  return Array.from({ length: characterSize.height }, (_, y) =>
    Array.from({ length: characterSize.width }, (_, x) => {
      const pixel = rows[y]?.[x] ?? '.';
      if (pixel !== '.') return pixel;
      return coloured(x - 1, y) || coloured(x + 1, y) || coloured(x, y - 1) || coloured(x, y + 1) ? 'K' : '.';
    }).join(''),
  );
};
const figure = (...layers: string[][]) => outline(stack(...layers));

