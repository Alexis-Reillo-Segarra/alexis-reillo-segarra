/** How many pixels he rises at each frame of the stride: highest as he passes over the straight leg. */
const LIFT = [-1, -1, 0, -1];
/** Where his hand is at each frame: the arm swings against the leg on the same side. */
const SWING = [-4, -3, 0, 3, 4, 3, 0, -3];

/** The leg nearer the viewer is lit, the far one sits in shadow: that is what tells the two halves of the cycle apart. */
const FAR_LEG: Record<string, string> = { Q: 'G', G: 'g', g: 'j', W: 'N', N: 'n' };
const far = (rows: string[]) => outline(rows.map((row) => row.replace(/[QGgWN]/g, (colour) => FAR_LEG[colour])));

/** Swings the side-view arm from the shoulder: the hand ends `by` pixels forward (or back, if negative). */
const swing = (rows: string[], by: number) =>
  rows.map((row, y) => {
    const shift = y < 54 || y > 70 ? 0 : Math.round((by * (y - 53)) / 17);
    if (!shift) return row;
    const torso = row.slice(22, 42);
    const moved =
      shift > 0 ? torso[0].repeat(shift) + torso.slice(0, -shift) : torso.slice(-shift) + torso.at(-1)!.repeat(-shift);
    return row.slice(0, 22) + moved + row.slice(42);
  });

/** A frame of the walk: the far leg, the near one over it, and the body over the tops of both. */
const step = (frame: number) => {
  const lift = LIFT[frame % 4];
  // The body ends at the hips, so the thighs are seen to move.
  const top = swing(sideTop, SWING[frame]).slice(0, 75);
  return figure(far(stride[(frame + 4) % 8]), outline(stride[frame]), lift < 0 ? lower(top, -lift) : top.slice(lift));
};

