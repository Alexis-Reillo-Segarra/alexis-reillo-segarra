/** Parachute canopy (96 wide), striped in the accent colour. */
export const canopy = Array.from({ length: 36 }, (_, y) => {
  const half = (row: number) => (row < 0 ? -1 : Math.round(Math.sqrt(1 - ((35 - row) / 36) ** 2) * 47));
  return Array.from({ length: 96 }, (_, x) => {
    const d = Math.abs(x - 47.5);
    if (d > half(y)) return '.';
    if (d > half(y) - 1 || d > half(y - 1) || y === 35) return 'K';
    return Math.floor(x / 16) % 2 ? 'W' : 'A';
  }).join('');
});

