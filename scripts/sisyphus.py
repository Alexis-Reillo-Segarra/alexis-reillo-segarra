"""Sisyphus in ASCII: the drawing behind the site, the README banner, the link preview and the favicon.

All of it comes from one ink drawing (dark strokes on light paper), redrawn as light glyphs on GitHub's
dark canvas colour, so the README banner melts into a dark-mode profile. The glyphs are Inconsolata,
the site's own font, read straight from node_modules.

    python3 -m pip install pillow numpy
    python3 scripts/sisyphus.py path/to/drawing.png

Writes src/data/sisyphus.ts, assets/sisyphus.jpg, public/og.png, public/favicon.png and
public/apple-touch-icon.png.
"""

import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'node_modules/@fontsource-variable/inconsolata/files/inconsolata-latin-wght-normal.woff2'
BG = np.array([13, 17, 23], np.float32) / 255  # #0d1117
FG = np.array([230, 237, 243], np.float32) / 255  # #e6edf3
MUTED = (139, 148, 158)  # #8b949e
RAMP = '.=+xX80S#@'  # sparse to dense
LINE = 2.2  # a glyph cell's height over its width: Inconsolata is 0.5em wide, set at line-height 1.1
LEVELS = 6  # brightness steps the site styles, `.l1` to `.l6`
EMPTY = 0.035  # a cell with less ink than this stays blank


def blur(a, radius):
    im = Image.fromarray(np.clip(a * 255, 0, 255).astype(np.uint8))
    return np.asarray(im.filter(ImageFilter.GaussianBlur(radius)), np.float32) / 255


def font(size, weight):
    f = ImageFont.truetype(str(FONT), size)
    f.set_variation_by_axes([weight])
    return f


def ink_map(path):
    """The drawing as 0 (paper) to 1 (solid ink), cropped to its strokes. Expects bare paper along the top."""
    im = Image.open(path).convert('RGBA')
    grey = Image.alpha_composite(Image.new('RGBA', im.size, (185, 185, 185, 255)), im).convert('L')
    a = np.asarray(grey, np.float32) / 255
    paper = float(np.median(a[: a.shape[0] // 6]))
    # Grainy paper: its specks reach ~0.16 of the way to black, solid strokes ~0.8
    darkness = np.clip((paper - blur(a, 1.2)) / paper, 0, 1)
    ink = np.clip((darkness - 0.16) / 0.62, 0, 1)
    ys, xs = np.where(blur(ink, 3) > 0.12)
    pad = 12
    return ink[max(ys.min() - pad, 0) : ys.max() + pad, max(xs.min() - pad, 0) : xs.max() + pad]


def cells(ink, cols, rows):
    """The mean ink under each glyph cell, with lone specks of paper grain wiped back to nothing."""
    im = Image.fromarray((ink * 255).astype(np.uint8)).resize((cols, rows), Image.BOX)
    m = np.asarray(im, np.float32) / 255
    inked = np.pad(m >= EMPTY, 1)
    neighbours = sum(np.roll(np.roll(inked, dy, 0), dx, 1) for dy in (-1, 0, 1) for dx in (-1, 0, 1)) - inked
    m[(neighbours[1:-1, 1:-1] == 0) & (m < 0.15)] = 0
    return m


def strength(m):
    """Ink to brightness. Squared, so solid ink (the figure) stays bright and the boulder's scribbles drop back."""
    return min(1.0, m**2 * 1.3)


def glyph(s, rng):
    return RAMP[int(np.clip(s + rng.normal(0, 0.05), 0, 0.999) * len(RAMP))]


# ---------------------------------------------------------------------------------------------- site


def site_art(ink, rows, rng):
    """Rows of glyphs for the site to set in type, and each glyph's brightness level."""
    cols = round(ink.shape[1] / (ink.shape[0] / rows / LINE))
    glyphs, levels = [], []
    for row in cells(ink, cols, rows):
        g, lv = '', ''
        for m in row:
            if m < EMPTY:
                g, lv = g + ' ', lv + '0'
            else:
                s = strength(m)
                g, lv = g + glyph(s, rng), lv + str(1 + min(LEVELS - 1, int(s * LEVELS)))
        end = len(g.rstrip())
        glyphs.append(g[:end])
        levels.append(lv[:end])
    return cols, glyphs, levels


def write_ts(path, cols, glyphs, levels):
    def strings(rows):
        return '\n'.join(f"    '{row}'," for row in rows)

    path.write_text(f"""// Generated by scripts/sisyphus.py from the Sisyphus drawing: regenerate it rather than edit it.

export interface AsciiArt {{
  cols: number;
  rows: number;
  /** One string per row; a space is bare canvas. */
  glyphs: string[];
  /** Each glyph's brightness, from '1' (faint) to '{LEVELS}' (solid ink), in step with `glyphs`. */
  levels: string[];
}}

export const sisyphus: AsciiArt = {{
  cols: {cols},
  rows: {len(glyphs)},
  glyphs: [
{strings(glyphs)}
  ],
  levels: [
{strings(levels)}
  ],
}};
""")


# ---------------------------------------------------------------------------------------------- images


def place(ink, size, height, centre_x=0.5):
    """`ink` scaled to `height` of a frame of `size`, its middle at `centre_x` across the frame."""
    w_frame, h_frame = size
    k = height * h_frame / ink.shape[0]
    w, h = round(ink.shape[1] * k), round(ink.shape[0] * k)
    im = Image.fromarray((ink * 255).astype(np.uint8)).resize((w, h), Image.LANCZOS)
    frame = np.zeros((h_frame, w_frame), np.float32)
    x, y = round(centre_x * w_frame - w / 2), (h_frame - h) // 2
    frame[y : y + h, x : x + w] = np.asarray(im, np.float32) / 255
    return frame


def render(frame, cell, rng):
    """Light glyphs over a soft glow of the drawing, on the dark canvas."""
    h, w = frame.shape
    under = blur(frame, 3) ** 2
    light = blur(under, 5) * 0.24 + blur(under, 40) * 0.07
    out = Image.fromarray((np.clip(BG + (FG - BG) * light[..., None], 0, 1) * 255).astype(np.uint8)).convert('RGBA')

    cols, rows = int(w / cell), int(h / (cell * LINE))
    f = font(round(cell * 2), 700)
    text = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(text)
    for r, row in enumerate(cells(frame, cols, rows)):
        for c, m in enumerate(row):
            if m < EMPTY:
                continue
            s = strength(m)
            colour = (BG + (FG - BG) * (0.25 + 0.75 * s)) * 255
            draw.text((c * cell, r * cell * LINE), glyph(s, rng), font=f,
                      fill=tuple(colour.astype(int)) + (int(90 + 165 * s),))
    glow = np.asarray(text.filter(ImageFilter.GaussianBlur(cell * 0.36))) * [1, 1, 1, 0.6]
    out = Image.alpha_composite(out, Image.fromarray(glow.astype(np.uint8)))
    out = np.asarray(Image.alpha_composite(out, text).convert('RGB'), np.float32)

    # Fine grain that fades out before the border, so the edges stay exactly the canvas colour
    y, x = np.mgrid[0:h, 0:w]
    fade = np.clip(np.minimum.reduce([x, w - 1 - x, y, h - 1 - y]) / (w / 22), 0, 1)
    out += (rng.normal(0, 2.5, (h, w)) * fade)[..., None]
    return Image.fromarray(np.clip(np.round(out), 0, 255).astype(np.uint8))


def preview(ink, rng):
    """The link preview: the drawing on the right, who it belongs to on the left."""
    im = render(place(ink, (1200, 630), 0.86, centre_x=0.72), 7, rng)
    draw = ImageDraw.Draw(im)
    draw.text((72, 66), 'alexisreillo.dev', font=font(24, 500), fill=MUTED)
    draw.text((72, 452), 'Alexis Reillo', font=font(50, 600), fill=tuple((FG * 255).astype(int)))
    draw.text((72, 522), 'FullStack Developer · AI Engineer', font=font(26, 400), fill=MUTED)
    return im


def icon(side, rounded):
    """An `@`, the densest glyph in the drawing, light on the dark canvas."""
    big = side * 4
    im = Image.new('RGBA', (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(im)
    canvas = tuple((BG * 255).astype(int))
    if rounded:
        draw.rounded_rectangle((0, 0, big - 1, big - 1), radius=big * 0.22, fill=canvas)
    else:
        draw.rectangle((0, 0, big, big), fill=canvas)
    draw.text((big / 2, big * 0.47), '@', font=font(round(big * 0.9), 700), anchor='mm',
              fill=tuple((FG * 255).astype(int)))
    return im.resize((side, side), Image.LANCZOS)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('drawing', type=Path, help='the ink drawing: dark strokes on light paper')
    args = parser.parse_args()

    ink = ink_map(args.drawing)
    rng = np.random.default_rng(5)

    cols, glyphs, levels = site_art(ink, 52, rng)
    write_ts(ROOT / 'src/data/sisyphus.ts', cols, glyphs, levels)

    banner = render(place(ink, (2000, 1125), 0.84), 11, rng)
    banner.save(ROOT / 'assets/sisyphus.jpg', quality=92, subsampling=0, optimize=True, progressive=True)
    preview(ink, rng).save(ROOT / 'public/og.png', optimize=True)
    icon(64, rounded=True).save(ROOT / 'public/favicon.png', optimize=True)
    icon(180, rounded=False).convert('RGB').save(ROOT / 'public/apple-touch-icon.png', optimize=True)


if __name__ == '__main__':
    main()
